drop policy if exists "Public can read current app state" on public.app_state;
create policy "Public can read current app state"
on public.app_state
for select
to anon, authenticated
using (true);

drop policy if exists "Admins can read app state history" on public.app_state_history;
create policy "Admins can read app state history"
on public.app_state_history
for select
to authenticated
using (public.has_admin_role('referee'));

drop policy if exists "Admins can create app state history" on public.app_state_history;
create policy "Admins can create app state history"
on public.app_state_history
for insert
to authenticated
with check (public.has_admin_role('referee'));

drop policy if exists "Sysadmins can prune app state history" on public.app_state_history;
create policy "Sysadmins can prune app state history"
on public.app_state_history
for delete
to authenticated
using (public.has_admin_role('sysadmin'));

drop policy if exists "Admins can read own profile" on public.profiles;
create policy "Admins can read own profile"
on public.profiles
for select
to authenticated
using (user_id = auth.uid() and active = true);

drop policy if exists "Sysadmins can read all profiles" on public.profiles;
create policy "Sysadmins can read all profiles"
on public.profiles
for select
to authenticated
using (public.has_admin_role('sysadmin'));

drop policy if exists "Sysadmins can update profiles" on public.profiles;
create policy "Sysadmins can update profiles"
on public.profiles
for update
to authenticated
using (public.has_admin_role('sysadmin'))
with check (public.has_admin_role('sysadmin'));

drop policy if exists "Admins can read audit log" on public.audit_log;
create policy "Admins can read audit log"
on public.audit_log
for select
to authenticated
using (public.has_admin_role('referee'));

grant usage on schema public to anon, authenticated;
grant select on public.app_state to anon, authenticated;
grant select on public.profiles to authenticated;
grant select on public.audit_log to authenticated;
grant select, insert on public.app_state_history to authenticated;
grant delete on public.app_state_history to authenticated;
grant execute on function public.has_admin_role(text) to authenticated;
grant execute on function public.log_audit_event(text, text, text, jsonb) to authenticated;
grant execute on function public.update_state_versioned(integer, jsonb) to authenticated;
grant execute on function public.replace_state_admin(jsonb, text) to authenticated;

